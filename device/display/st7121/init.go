// Package st7121 implements the vendor initialization sequence for an ST7121
// display controller. Board packages provide the DSI command transport.
package st7121

// Transport sends DCS commands and waits while the panel applies them.
type Transport interface {
	Command(command byte, data []byte)
	Delay(milliseconds int)
}

