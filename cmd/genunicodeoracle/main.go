// Command genunicodeoracle records independent Go Unicode 15 oracle digests.
// Run with GOTOOLCHAIN=go1.25.5 from the repository root. Never derive expected
// results from Renvo's tables: these tests must detect errors in those tables.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/binary"
	"fmt"
	"go/format"
	"os"
	"unicode"
)

type property struct {
	name, expression string
	evaluate         func(rune) uint32
}

func boolean(f func(rune) bool) func(rune) uint32 {
	return func(r rune) uint32 {
		if f(r) {
			return 1
		}
		return 0
	}
}
func mapping(f func(rune) rune) func(rune) uint32 {
	return func(r rune) uint32 { return uint32(f(r)) }
}
func main() {
	if unicode.Version != "15.0.0" {
		panic("oracle requires Unicode 15.0.0: use GOTOOLCHAIN=go1.25.5")
	}
	emit("internal/syntax/unicode_snapshot_test.go", "syntax", []property{
		{"IsLetter", "unicodeRangeContains(unicodeLetterRanges, int(r))", boolean(unicode.IsLetter)},
		{"IsDigit", "unicodeRangeContains(unicodeDigitRanges, int(r))", boolean(unicode.IsDigit)},
		{"IsUpper", "unicodeRangeContains(unicodeUpperRanges, int(r))", boolean(unicode.IsUpper)},
	}, false)
	emit("std/unicode/unicode_host_test.go", "unicode", []property{
		{"IsLetter", "IsLetter(r)", boolean(unicode.IsLetter)},
		{"IsDigit", "IsDigit(r)", boolean(unicode.IsDigit)},
		{"IsSpace", "IsSpace(r)", boolean(unicode.IsSpace)},
		{"IsUpper", "IsUpper(r)", boolean(unicode.IsUpper)},
		{"IsLower", "IsLower(r)", boolean(unicode.IsLower)},
		{"IsTitle", "IsTitle(r)", boolean(unicode.IsTitle)},
		{"ToUpper", "uint32(ToUpper(r))", mapping(unicode.ToUpper)},
		{"ToLower", "uint32(ToLower(r))", mapping(unicode.ToLower)},
		{"ToTitle", "uint32(ToTitle(r))", mapping(unicode.ToTitle)},
		{"SimpleFold", "uint32(SimpleFold(r))", mapping(unicode.SimpleFold)},
	}, true)
}
func emit(path, pkg string, properties []property, versionCheck bool) {
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by GOTOOLCHAIN=go1.25.5 go run ./cmd/genunicodeoracle; DO NOT EDIT.")
	fmt.Fprintln(&out, "// Oracle: Go unicode 15.0.0. SHA-256 blocks cover every rune from -1 through 0x110000.")
	fmt.Fprintln(&out, "// Each result is encoded as a little-endian uint32; no target tables are used to generate expectations.")
	fmt.Fprintln(&out, "//go:build !renvo")
	fmt.Fprintf(&out, "\npackage %s\nimport (\"crypto/sha256\"; \"encoding/binary\"; \"fmt\"; \"testing\")\n", pkg)
	fmt.Fprintln(&out, "func TestUnicode15Snapshot(t *testing.T) {")
	if versionCheck {
		fmt.Fprintln(&out, `if Version != "15.0.0" { t.Fatal("update the independent oracle when intentionally upgrading Unicode", Version) }`)
	}
	fmt.Fprintln(&out, "for _, tc := range []struct { name string; evaluate func(rune) uint32; digests []string }{")
	for _, p := range properties {
		fmt.Fprintf(&out, "{name:%q, evaluate:func(r rune)uint32{", p.name)
		if len(p.expression) >= 6 && p.expression[:6] == "uint32" {
			fmt.Fprintf(&out, "return %s", p.expression)
		} else {
			fmt.Fprintf(&out, "if %s {return 1};return 0", p.expression)
		}
		fmt.Fprintln(&out, "},digests:[]string{")
		for start := rune(-1); start <= unicode.MaxRune+1; start += 65536 {
			end := start + 65536
			if end > unicode.MaxRune+2 {
				end = unicode.MaxRune + 2
			}
			h := sha256.New()
			var word [4]byte
			for r := start; r < end; r++ {
				binary.LittleEndian.PutUint32(word[:], p.evaluate(r))
				h.Write(word[:])
			}
			fmt.Fprintf(&out, "%q,\n", fmt.Sprintf("%x", h.Sum(nil)))
		}
		fmt.Fprintln(&out, "}},")
	}
	out.WriteString(`} {
  t.Run(tc.name,func(t *testing.T){
   for block,want:=range tc.digests {
    start:=rune(-1+block*65536)
    end:=start+65536
    if end>0x110001 {end=0x110001}
    h:=sha256.New()
    var word [4]byte
    for r:=start;r<end;r++ {binary.LittleEndian.PutUint32(word[:],tc.evaluate(r));h.Write(word[:])}
    if got:=fmt.Sprintf("%x",h.Sum(nil));got!=want {t.Fatalf("Unicode 15 %s differs in range %U..%U: %s, want %s",tc.name,start,end-1,got,want)}
   }
  })
 }
}`)
	data, err := format.Source(out.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile(path, data, 0644); err != nil {
		panic(err)
	}
}
