// Command genstdunicode generates portable Unicode data, not runtime wrappers
// around the host library. Run from the Renvo repository root.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"unicode"
)

// Four printable six-bit digits encode a signed 24-bit table value.
func appendValue(data []byte, value int64) []byte {
	if value < -1<<23 || value >= 1<<23 {
		panic("Unicode value exceeds packed range")
	}
	for shift := 18; shift >= 0; shift -= 6 {
		data = append(data, byte((value>>shift)&63)+32)
	}
	return data
}

func main() {
	check := flag.Bool("check", false, "verify the checked-in Unicode snapshot")
	flag.Parse()
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by go run ./cmd/genstdunicode; DO NOT EDIT.\npackage unicode")
	fmt.Fprintf(&out, "const Version = %q\n", unicode.Version)
	for _, item := range []struct {
		name  string
		table *unicode.RangeTable
	}{
		{"letterRanges", unicode.Letter}, {"digitRanges", unicode.Digit}, {"spaceRanges", unicode.White_Space},
		{"upperRanges", unicode.Upper}, {"lowerRanges", unicode.Lower}, {"titleRanges", unicode.Title},
	} {
		var packed []byte
		for _, r := range item.table.R16 {
			for _, v := range []uint16{r.Lo, r.Hi, r.Stride} {
				packed = appendValue(packed, int64(v))
			}
		}
		for _, r := range item.table.R32 {
			for _, v := range []uint32{r.Lo, r.Hi, r.Stride} {
				packed = appendValue(packed, int64(v))
			}
		}
		fmt.Fprintf(&out, "var %s = %q\n", item.name, string(packed))
	}
	var cases, folds []byte
	for _, r := range unicode.CaseRanges {
		for _, v := range []int64{int64(r.Lo), int64(r.Hi), int64(r.Delta[0]), int64(r.Delta[1]), int64(r.Delta[2])} {
			cases = appendValue(cases, v)
		}
	}
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if next := unicode.SimpleFold(r); next != r {
			folds = appendValue(folds, int64(r))
			folds = appendValue(folds, int64(next))
		}
	}
	fmt.Fprintf(&out, "var caseRanges = %q\nvar foldPairs = %q\n", string(cases), string(folds))
	data, err := format.Source(out.Bytes())
	if err != nil {
		panic(err)
	}
	const path = "std/unicode/tables.go"
	if *check {
		existing, err := os.ReadFile(path)
		if err != nil || !bytes.Equal(existing, data) {
			panic("Unicode snapshot differs; regenerate with the intended Go Unicode version")
		}
		return
	}
	if err := os.WriteFile(path, data, 0644); err != nil {
		panic(err)
	}
}
