// Command rfegen materializes the importable x86 CPU from its authored RFE.
// This is a development-time generator; applications never compile or extract
// source, start subprocesses, or use temporary files to execute an RFE.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"renvo.dev/internal/rfe"
	"sort"
	"strings"
)

var pruneGenerated bool

func main() {
	check := flag.Bool("check", false, "check without writing")
	flag.BoolVar(&pruneGenerated, "prune", false, "remove obsolete files bearing this generator header")
	flag.Parse()
	if err := generate(*check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
func generate(check bool) error {
	data, err := os.ReadFile("emulators/x86.rfe")
	if err != nil {
		return err
	}
	p, err := rfe.Decode(data)
	if err != nil {
		return err
	}
	if len(p.Manifest.Requires) != 0 {
		return fmt.Errorf("x86 generator requires a standalone CPU archive")
	}
	names := []string{}
	for n := range p.Files {
		if strings.HasSuffix(n, ".go") {
			names = append(names, n)
		}
	}
	// Reject unexpected generated files rather than silently leaving code from
	// removed archive sections in the public package.
	entries, err := os.ReadDir("rfe/x86")
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	for _, entry := range entries {
		if strings.HasSuffix(entry.Name(), ".go") && p.Files[entry.Name()] == nil {
			if !check && pruneGenerated {
				name := filepath.Join("rfe/x86", entry.Name())
				old, err := os.ReadFile(name)
				if err != nil {
					return err
				}
				if !bytes.HasPrefix(old, []byte("// Code generated by go run ./cmd/rfegen from emulators/x86.rfe; DO NOT EDIT.\n")) {
					return fmt.Errorf("refusing to prune non-generated source: %s", name)
				}
				if err := os.Remove(name); err != nil {
					return err
				}
				continue
			}
			return fmt.Errorf("unexpected generated source: rfe/x86/%s", entry.Name())
		}
	}
	sort.Strings(names)
	if !check {
		if err := os.MkdirAll("rfe/x86", 0755); err != nil {
			return err
		}
	}
	for _, n := range names {
		content, err := format.Source(p.Files[n])
		if err != nil {
			return fmt.Errorf("%s: %w", n, err)
		}
		content = append([]byte("// Code generated by go run ./cmd/rfegen from emulators/x86.rfe; DO NOT EDIT.\n\n"), content...)
		dest := filepath.Join("rfe/x86", n)
		old, _ := os.ReadFile(dest)
		if bytes.Equal(old, content) {
			continue
		}
		if check {
			return fmt.Errorf("stale generated RFE source: %s", dest)
		}
		if err := os.WriteFile(dest, content, 0644); err != nil {
			return err
		}
	}
	return nil
}
