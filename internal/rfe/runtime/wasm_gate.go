func (w *wasmCode) gateReject() {
	w.byte(0x04)
	w.byte(0x40)
	w.byte(0x41)
	w.byte(0x7f) // signed i32 -1
	w.byte(0x0f)
	w.byte(0x0b)
}

// Packed records keep the original fixed four metadata pages and 16-byte
// entry stride. Only the worker writes them: words[8:0], memory[9], run[10],
// proof[11], count[20:12]; context extent at +4, full PC at +8. Admission is
// write-once per entry; a different owner revokes every old exported proof.
func emitWasmGateProof() []byte {
	var w wasmCode
	w.u32(1)
	w.u32(1)
	w.byte(0x7f) // local 4: checked entry offset
	w.i32(0)
	w.mem(0x28, 2, 0)
	w.byte(0x23)
	w.u32(0)
	w.byte(0x47)
	w.proofReject()
	w.get(1)
	w.i64(16)
	w.byte(0x54)
	w.get(1)
	w.i64(16384 * 16)
	w.byte(0x5a)
	w.byte(0x72)
	w.get(1)
	w.i64(15)
	w.byte(0x83)
	w.byte(0x50)
	w.byte(0x45)
	w.byte(0x72)
	w.proofReject()
	w.get(1)
	w.byte(0xa7)
	w.set(4)
	w.get(4)
	w.mem(0x28, 2, 0)
	w.i32(3072)
	w.byte(0x71)
	w.i32(3072)
	w.byte(0x47)
	w.proofReject()
	w.get(4)
	w.mem(0x28, 2, 0)
	w.i32(511)
	w.byte(0x71)
	w.get(3)
	w.byte(0x47)
	w.proofReject()
	w.get(4)
	w.mem(0x28, 2, 0)
	w.i32(12)
	w.byte(0x76)
	w.i32(511)
	w.byte(0x71)
	w.byte(0xad)
	w.get(2)
	w.byte(0x52)
	w.proofReject()
	w.get(4)
	w.mem(0x29, 3, 8)
	w.get(0)
	w.byte(0x51)
	w.byte(0x0b)
	return w.code
}
func (w *wasmCode) proofReject() {
	w.byte(0x04)
	w.byte(0x40)
	w.i32(0)
	w.byte(0x0f)
	w.byte(0x0b)
}
