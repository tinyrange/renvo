type sourceDescriptor struct {
	Name                string   `json:"name"`
	Backend             string   `json:"backend"`
	BackendID           int      `json:"backend_id"`
	Constant            string   `json:"constant"`
	Aliases             []string `json:"aliases"`
	Family              string   `json:"family"`
	OS                  string   `json:"os"`
	OSID                int      `json:"os_id"`
	ISA                 string   `json:"isa"`
	ISAID               int      `json:"isa_id"`
	WordBits            int      `json:"word_bits"`
	PointerBits         int      `json:"pointer_bits"`
	CodePointerBits     int      `json:"code_pointer_bits"`
	FunctionPointerBits int      `json:"function_pointer_bits"`
	MaxAlign            int      `json:"max_align"`
	Endian              string   `json:"endian"`
	ABI                 string   `json:"abi"`
	Image               string   `json:"image"`
	Runtime             []string `json:"runtime"`
	Tags                []string `json:"tags"`
	Advertised          bool     `json:"advertised"`
	Virtual             bool     `json:"virtual"`
	DefaultArena        int      `json:"default_arena"`
	ReleaseArtifact     string   `json:"release_artifact"`
	IDE                 bool     `json:"ide"`
	Capabilities        []string `json:"capabilities"`
	Definition          [32]byte `json:"-"`
	Descriptor          int      `json:"-"`
	DeclarativeBytes    int      `json:"-"`
	ReachableGoBytes    int      `json:"-"`
	CatalogGoBytes      int      `json:"-"`
	ReachableGoDecls    int      `json:"-"`
	CatalogGoDecls      int      `json:"-"`
}

func main() {
	root, err := repositoryRoot()
	must(err)
	data, err := os.ReadFile(filepath.Join(root, "internal", "targetinfo", "targets.json"))
	must(err)
	var descriptors []sourceDescriptor
	must(json.Unmarshal(data, &descriptors))
	must(mergeMachineDefinitions(root, descriptors))
	must(validate(descriptors))
	must(writeFormatted(filepath.Join(root, "internal", "targetinfo", "registry_generated.go"), frontendSource(descriptors)))
	must(writeFormatted(filepath.Join(root, "internal", "driver", "target_help_generated.go"), driverHelpSource(descriptors)))
	must(updatePolicyProjection(filepath.Join(root, "backend", "compiler_target_policy_impl.go"), descriptors))
	must(writeFormatted(filepath.Join(root, "backend", "compiler_target_registry_impl.go"), backendSource(descriptors)))
	must(os.WriteFile(filepath.Join(root, "backend", "docs", "machine-definitions.generated.md"), documentationSource(descriptors), 0o644))
}

func documentationSource(descriptors []sourceDescriptor) []byte {
	var out bytes.Buffer
	out.WriteString("# Built-in machine definitions\n\n")
	out.WriteString("<!-- Code generated by go generate ./internal/targetinfo; DO NOT EDIT. -->\n\n")
	out.WriteString("This is the frontend-visible completeness projection of the checked-in `.rtg` definitions. ")
	out.WriteString("The definition column is the target semantic identity. ")
	out.WriteString("Per-target metrics are review aids and do not loosen or replace performance gates. ")
	out.WriteString("Deduplicated native embedded-Go volume is reported separately as a non-enforcing code-hygiene metric. ")
	out.WriteString("Go volume is shown as reachable/entrypoint bytes and declarations.\n\n")
	out.WriteString("| Target | Family | OS | ISA | Int/data/code/function bits | Max align | ABI | Output | Runtime operations | Capabilities | Declarative bytes | Go bytes | Go declarations | Definition |\n")
	out.WriteString("|---|---|---|---|---:|---:|---|---|---|---|---:|---:|---:|---|\n")
	for _, descriptor := range descriptors {
		fmt.Fprintf(&out, "| `%s` | `%s` | `%s` | `%s` | %d/%d/%d/%d | %d | `%s` | `%s` | %s | %s | %d | %d/%d | %d/%d | `%s` |\n",
			descriptor.Name, descriptor.Family, descriptor.OS, descriptor.ISA,
			descriptor.WordBits, descriptor.PointerBits, descriptor.CodePointerBits,
			descriptor.FunctionPointerBits, descriptor.MaxAlign, descriptor.ABI,
			descriptor.Image, markdownCodeList(descriptor.Runtime),
			markdownCodeList(descriptor.Capabilities), descriptor.DeclarativeBytes,
			descriptor.ReachableGoBytes, descriptor.CatalogGoBytes,
			descriptor.ReachableGoDecls, descriptor.CatalogGoDecls,
			rtg.HashText(descriptor.Definition))
	}
	return out.Bytes()
}

func markdownCodeList(values []string) string {
	if len(values) == 0 {
		return "—"
	}
	out := "`" + values[0] + "`"
	for i := 1; i < len(values); i++ {
		out += ", `" + values[i] + "`"
	}
	return out
}

func mergeMachineDefinitions(root string, descriptors []sourceDescriptor) error {
	paths, err := filepath.Glob(filepath.Join(root, "backend", "definitions", "*.rtg"))
	if err != nil {
		return err
	}
	sort.Strings(paths)
	type resolvedMachine struct {
		descriptor rtg.TargetDescriptor
		metrics    rtg.TargetMetrics
	}
	targets := make(map[string]resolvedMachine)
	for _, path := range paths {
		source, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if !bytes.HasPrefix(bytes.TrimSpace(source), []byte("definition ")) {
			continue
		}
		parsed := rtg.ParseImports(source, path, machineDefinitionImportLoader{})
		if !parsed.Ok {
			return fmt.Errorf("%s: %s", filepath.Base(path), parsed.Diagnostics[0].Message)
		}
		if !documentDeclaresTarget(parsed) {
			continue
		}
		resolved := rtg.ResolveDefinitions(parsed)
		if !resolved.Ok {
			return fmt.Errorf("%s: %s", filepath.Base(path), resolved.Diagnostics[0].Message)
		}
		for _, target := range resolved.Targets {
			name := target.Descriptor.Name
			if _, exists := targets[name]; exists {
				return fmt.Errorf("duplicate definition target %q", name)
			}
			targets[name] = resolvedMachine{
				descriptor: target.Descriptor,
				metrics:    rtg.MeasureTarget(resolved.Document, target),
			}
		}
	}
	for i := range descriptors {
		resolved, ok := targets[descriptors[i].Name]
		if !ok {
			return fmt.Errorf("registry policy target %q has no machine definition", descriptors[i].Name)
		}
		delete(targets, descriptors[i].Name)
		machine := resolved.descriptor
		descriptors[i].Aliases = append([]string(nil), machine.Aliases...)
		descriptors[i].Family = machine.Family
		descriptors[i].OS = machine.OS
		descriptors[i].ISA = machine.ISA
		descriptors[i].WordBits = machine.WordBits
		descriptors[i].PointerBits = machine.PointerBits
		descriptors[i].CodePointerBits = machine.CodePointerBits
		descriptors[i].FunctionPointerBits = machine.FunctionPointerBits
		descriptors[i].MaxAlign = machine.MaxAlign
		descriptors[i].Endian = machine.Endian
		descriptors[i].ABI = machine.ABI
		descriptors[i].Image = machine.OutputKind
		descriptors[i].Tags = append([]string(nil), machine.BuildTags...)
		descriptors[i].Capabilities = append([]string(nil), machine.Capabilities...)
		descriptors[i].Runtime = append([]string(nil), machine.RuntimeOps...)
		if contains(machine.Capabilities, "hosted") {
			descriptors[i].Runtime = append(descriptors[i].Runtime, "hosted")
		}
		descriptors[i].Definition = machine.Definition
		descriptors[i].Descriptor = machine.Version
		descriptors[i].DefaultArena = machine.ArenaDefault
		descriptors[i].DeclarativeBytes = resolved.metrics.DeclarativeBytes
		descriptors[i].ReachableGoBytes = resolved.metrics.ReachableGoBytes
		descriptors[i].CatalogGoBytes = resolved.metrics.CatalogGoBytes
		descriptors[i].ReachableGoDecls = resolved.metrics.ReachableGoDecls
		descriptors[i].CatalogGoDecls = resolved.metrics.CatalogGoDecls
		if descriptors[i].Backend == "" {
			descriptors[i].Backend = descriptors[i].Name
		}
	}
	for name := range targets {
		return fmt.Errorf("machine definition target %q has no registry policy", name)
	}
	return nil
}

func documentDeclaresTarget(document rtg.Document) bool {
	for i := 0; i < len(document.Declarations); i++ {
		if document.Declarations[i].Kind == rtg.DeclTarget {
			return true
		}
	}
	return false
}

type machineDefinitionImportLoader struct{}

func (machineDefinitionImportLoader) LoadImport(
	importingFilename string, importPath string,
) rtg.ImportSource {
	path := filepath.Clean(filepath.Join(filepath.Dir(importingFilename), importPath))
	source, err := os.ReadFile(path)
	return rtg.ImportSource{Source: source, Filename: path, Ok: err == nil}
}

func contains(values []string, value string) bool {
	for _, item := range values {
		if item == value {
			return true
		}
	}
	return false
}

