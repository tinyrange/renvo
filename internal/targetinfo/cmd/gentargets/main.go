package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

type sourceDescriptor struct {
	Name            string   `json:"name"`
	Backend         string   `json:"backend"`
	BackendID       int      `json:"backend_id"`
	Constant        string   `json:"constant"`
	Aliases         []string `json:"aliases"`
	OS              string   `json:"os"`
	OSID            int      `json:"os_id"`
	ISA             string   `json:"isa"`
	ISAID           int      `json:"isa_id"`
	WordBits        int      `json:"word_bits"`
	Endian          string   `json:"endian"`
	ABI             string   `json:"abi"`
	Image           string   `json:"image"`
	Runtime         []string `json:"runtime"`
	Tags            []string `json:"tags"`
	Advertised      bool     `json:"advertised"`
	Virtual         bool     `json:"virtual"`
	DefaultArena    int      `json:"default_arena"`
	ReleaseArtifact string   `json:"release_artifact"`
	IDE             bool     `json:"ide"`
}

func main() {
	root, err := repositoryRoot()
	must(err)
	data, err := os.ReadFile(filepath.Join(root, "internal", "targetinfo", "targets.json"))
	must(err)
	var descriptors []sourceDescriptor
	must(json.Unmarshal(data, &descriptors))
	must(validate(descriptors))
	must(writeFormatted(filepath.Join(root, "internal", "targetinfo", "registry_generated.go"), frontendSource(descriptors)))
	must(writeFormatted(filepath.Join(root, "internal", "driver", "target_help_generated.go"), driverHelpSource(descriptors)))
	must(updatePolicyProjection(filepath.Join(root, "backend", "compiler_target_policy_impl.go"), descriptors))
	must(writeFormatted(filepath.Join(root, "backend", "compiler_target_registry_impl.go"), backendSource(descriptors)))
}

func driverHelpSource(descriptors []sourceDescriptor) []byte {
	const prefix = "Usage: renvo -o <file> [-t <target>] [-backend <file.rtg|file.rtgb>] [-system <file.rtg>] [-mode=<mode>] [-tags <list>] [-arena-size <bytes>] [-s] [-emit-unit] [-emit-image] [-windows-gui] <package | file.go...>\n" +
		"       renvo run [build options] <script.go> [-- script arguments...]\n" +
		"       renvo test [build options] [package]\n" +
		"Options:\n" +
		"  -arena-size  set the generated program arena limit in bytes (256..1073741824)\n" +
		"  -backend     select and prepare a backend definition or prepared artifact\n" +
		"  -system      load target, binary-size, and arena limits from a hosted system profile\n" +
		"  -emit-unit   write the canonical linked Renvo unit without invoking a backend\n" +
		"  -emit-image  write a format-neutral linked image instead of an executable\n" +
		"  -mode        select executable (default) or kernel-module output\n" +
		"  -script      compile one file whose top-level statements form func main\n" +
		"  -windows-gui select the Windows GUI subsystem instead of the console subsystem\n" +
		"Source files:\n" +
		"  Explicit .go files must share one directory and package. Exactly the named files are used;\n" +
		"  build constraints and OS/architecture suffixes are ignored, while _test.go files are skipped.\n" +
		"Targets:\n  "
	const suffix = "Unsupported language/toolchain features:\n  generics, goroutines, channels, select, cgo\n"
	var advertised []string
	for _, descriptor := range descriptors {
		if descriptor.Advertised {
			advertised = append(advertised, descriptor.Name)
		}
	}
	return []byte("// Code generated by go generate ./internal/targetinfo; DO NOT EDIT.\n\npackage driver\n\nconst DefaultTarget = " +
		strconv.Quote(descriptors[0].Name) + "\nconst HelpText = " +
		strconv.Quote(prefix+strings.Join(advertised, " ")+"\n"+suffix))
}

func repositoryRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("repository root not found")
		}
		dir = parent
	}
}

func validate(descriptors []sourceDescriptor) error {
	names := make(map[string]bool)
	ids := make(map[int]bool)
	for _, descriptor := range descriptors {
		if descriptor.Name == "" || descriptor.Backend == "" || descriptor.OS == "" || descriptor.ISA == "" ||
			descriptor.WordBits == 0 || descriptor.Endian == "" || descriptor.ABI == "" || descriptor.Image == "" {
			return fmt.Errorf("incomplete target descriptor %q", descriptor.Name)
		}
		if names[descriptor.Name] {
			return fmt.Errorf("duplicate target name %q", descriptor.Name)
		}
		names[descriptor.Name] = true
		if descriptor.Constant != "" {
			if descriptor.BackendID < 1 || descriptor.OSID < 1 || descriptor.ISAID < 1 {
				return fmt.Errorf("incomplete backend projection for %q", descriptor.Name)
			}
			if ids[descriptor.BackendID] {
				return fmt.Errorf("duplicate backend ID %d", descriptor.BackendID)
			}
			ids[descriptor.BackendID] = true
		}
	}
	for id := 1; id <= len(ids); id++ {
		if !ids[id] {
			return fmt.Errorf("backend target IDs are not dense at %d", id)
		}
	}
	return nil
}

func frontendSource(descriptors []sourceDescriptor) []byte {
	var out bytes.Buffer
	out.WriteString("// Code generated by go generate ./internal/targetinfo; DO NOT EDIT.\n\npackage targetinfo\n\n")
	out.WriteString("const DefaultName = \"linux/amd64\"\n")
	out.WriteString("const AdvertisedHelp = ")
	var advertised []string
	for _, descriptor := range descriptors {
		if descriptor.Advertised {
			advertised = append(advertised, descriptor.Name)
		}
	}
	out.WriteString(strconv.Quote(strings.Join(advertised, " ") + "\n"))
	out.WriteString("\nfunc All() []Descriptor { return []Descriptor{\n")
	for _, descriptor := range descriptors {
		writeFrontendDescriptor(&out, descriptor)
		out.WriteString(",\n")
	}
	out.WriteString("} }\n\n")
	out.WriteString("func Lookup(name string) (Descriptor, bool) {\n")
	for _, descriptor := range descriptors {
		fmt.Fprintf(&out, "if name == %q", descriptor.Name)
		for _, alias := range descriptor.Aliases {
			fmt.Fprintf(&out, " || name == %q", alias)
		}
		out.WriteString(" { return ")
		writeFrontendDescriptor(&out, descriptor)
		out.WriteString(", true }\n")
	}
	out.WriteString("return Descriptor{}, false\n}\n\n")
	out.WriteString("func IsAdvertised(name string) bool { return ")
	first := true
	for _, descriptor := range descriptors {
		if !descriptor.Advertised {
			continue
		}
		if !first {
			out.WriteString(" || ")
		}
		fmt.Fprintf(&out, "name == %q", descriptor.Name)
		first = false
	}
	out.WriteString(" }\n\n")
	out.WriteString("func Backend(name string) string {\n")
	for _, descriptor := range descriptors {
		if descriptor.Backend != descriptor.Name {
			fmt.Fprintf(&out, "if name == %q { return %q }\n", descriptor.Name, descriptor.Backend)
		}
		for _, alias := range descriptor.Aliases {
			fmt.Fprintf(&out, "if name == %q { return %q }\n", alias, descriptor.Backend)
		}
	}
	out.WriteString("return name\n}\n\n")
	out.WriteString("func HasBuildTag(name string, tag string) bool {\n")
	for _, descriptor := range descriptors {
		fmt.Fprintf(&out, "if name == %q { return ", descriptor.Name)
		for i, tag := range descriptor.Tags {
			if i > 0 {
				out.WriteString(" || ")
			}
			fmt.Fprintf(&out, "tag == %q", tag)
		}
		out.WriteString(" }\n")
	}
	out.WriteString("return false\n}\n\n")
	out.WriteString("func DefaultArena(name string) int {\n")
	for _, descriptor := range descriptors {
		if descriptor.DefaultArena != 0 {
			fmt.Fprintf(&out, "if name == %q { return %d }\n", descriptor.Name, descriptor.DefaultArena)
		}
	}
	out.WriteString("return 0\n}\n\n")
	out.WriteString("func IDETargets() []string { return []string{")
	first = true
	for _, descriptor := range descriptors {
		if !descriptor.IDE {
			continue
		}
		if !first {
			out.WriteString(",")
		}
		out.WriteString(strconv.Quote(descriptor.Name))
		first = false
	}
	out.WriteString("} }\n")
	return out.Bytes()
}

func writeFrontendDescriptor(out *bytes.Buffer, descriptor sourceDescriptor) {
	fmt.Fprintf(out, "Descriptor{Name:%q, Backend:%q, Aliases:%#v, OS:%q, ISA:%q, WordBits:%d, Endian:%q, ABI:%q, Image:%q, Runtime:%#v, Tags:%#v, Advertised:%t, Virtual:%t, DefaultArena:%d, ReleaseArtifact:%q, IDE:%t}",
		descriptor.Name, descriptor.Backend, descriptor.Aliases, descriptor.OS, descriptor.ISA, descriptor.WordBits,
		descriptor.Endian, descriptor.ABI, descriptor.Image, descriptor.Runtime, descriptor.Tags, descriptor.Advertised,
		descriptor.Virtual, descriptor.DefaultArena, descriptor.ReleaseArtifact, descriptor.IDE)
}

func backendSource(descriptors []sourceDescriptor) []byte {
	var backend []sourceDescriptor
	for _, descriptor := range descriptors {
		if descriptor.Constant != "" {
			backend = append(backend, descriptor)
		}
	}
	sort.Slice(backend, func(i, j int) bool { return backend[i].BackendID < backend[j].BackendID })
	var out bytes.Buffer
	out.WriteString("// Code generated by go generate ./internal/targetinfo; DO NOT EDIT.\n\npackage main\n\n")
	out.WriteString("const renvoSupportedTargets = ")
	var supported []string
	for _, descriptor := range descriptors {
		if descriptor.Advertised && !descriptor.Virtual {
			supported = append(supported, descriptor.Name)
		}
	}
	out.WriteString(strconv.Quote(strings.Join(supported, ", ")))
	out.WriteString("\n\nfunc renvoParseTargetArg(target string) int {\n")
	for _, descriptor := range backend {
		fmt.Fprintf(&out, "if target == %q { return %s }\n", descriptor.Name, descriptor.Constant)
		for _, alias := range descriptor.Aliases {
			fmt.Fprintf(&out, "if target == %q { return %s }\n", alias, descriptor.Constant)
		}
	}
	out.WriteString("return 0\n}\n")
	return out.Bytes()
}

func updatePolicyProjection(path string, descriptors []sourceDescriptor) error {
	const begin = "// BEGIN GENERATED TARGET REGISTRY"
	const end = "// END GENERATED TARGET REGISTRY"
	source, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	start := bytes.Index(source, []byte(begin))
	finish := bytes.Index(source, []byte(end))
	if start < 0 || finish < start {
		return fmt.Errorf("target registry markers missing from %s", path)
	}
	finish += len(end)
	var backend []sourceDescriptor
	for _, descriptor := range descriptors {
		if descriptor.Constant != "" {
			backend = append(backend, descriptor)
		}
	}
	sort.Slice(backend, func(i, j int) bool { return backend[i].BackendID < backend[j].BackendID })
	var projection bytes.Buffer
	projection.WriteString(begin)
	projection.WriteByte('\n')
	for _, descriptor := range backend {
		fmt.Fprintf(&projection, "const %s = %d\n", descriptor.Constant, descriptor.BackendID)
	}
	projection.WriteString("\nconst targetOSTable = ")
	projection.WriteString(strconv.Quote(byteTable(backend, func(descriptor sourceDescriptor) int { return descriptor.OSID })))
	projection.WriteString("\nconst targetArchTable = ")
	projection.WriteString(strconv.Quote(byteTable(backend, func(descriptor sourceDescriptor) int { return descriptor.ISAID })))
	projection.WriteString("\nconst renvoTargetIntBitsTable = ")
	projection.WriteString(strconv.Quote(byteTable(backend, func(descriptor sourceDescriptor) int { return descriptor.WordBits })))
	projection.WriteByte('\n')
	projection.WriteString(end)
	updated := append([]byte{}, source[:start]...)
	updated = append(updated, projection.Bytes()...)
	updated = append(updated, source[finish:]...)
	return writeFormatted(path, updated)
}

func byteTable(descriptors []sourceDescriptor, value func(sourceDescriptor) int) string {
	data := make([]byte, len(descriptors)+1)
	for _, descriptor := range descriptors {
		data[descriptor.BackendID] = byte(value(descriptor))
	}
	return string(data)
}

func writeFormatted(path string, source []byte) error {
	formatted, err := format.Source(source)
	if err != nil {
		return fmt.Errorf("format %s: %w", path, err)
	}
	return os.WriteFile(path, formatted, 0o644)
}

func must(err error) {
	if err != nil {
		panic(err)
	}
}
