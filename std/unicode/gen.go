//go:build ignore

package main

import (
	"fmt"
	"os"
	"unicode"
)

func ranges16(out *os.File, name string, table *unicode.RangeTable) {
	fmt.Fprintf(out, "var %s = []rangeEntry{\n", name)
	for _, r := range table.R16 {
		fmt.Fprintf(out, "{0x%x,0x%x,0x%x},\n", r.Lo, r.Hi, r.Stride)
	}
	for _, r := range table.R32 {
		fmt.Fprintf(out, "{0x%x,0x%x,0x%x},\n", r.Lo, r.Hi, r.Stride)
	}
	fmt.Fprintln(out, "}")
}
func cases(out *os.File, name string, convert func(rune) rune) {
	fmt.Fprintf(out, "var %s = []caseEntry{\n", name)
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if mapped := convert(r); mapped != r {
			fmt.Fprintf(out, "{0x%x,0x%x},\n", r, mapped)
		}
	}
	fmt.Fprintln(out, "}")
}
func main() {
	out, err := os.Create("tables_generated.go")
	if err != nil {
		panic(err)
	}
	defer out.Close()
	fmt.Fprintln(out, "// Code generated by go generate; DO NOT EDIT.\n\npackage unicode")
	ranges16(out, "letterTable", unicode.Letter)
	ranges16(out, "digitTable", unicode.Digit)
	ranges16(out, "numberTable", unicode.Number)
	ranges16(out, "spaceTable", unicode.White_Space)
	ranges16(out, "upperTable", unicode.Upper)
	ranges16(out, "lowerTable", unicode.Lower)
	cases(out, "toUpperTable", unicode.ToUpper)
	cases(out, "toLowerTable", unicode.ToLower)
}
